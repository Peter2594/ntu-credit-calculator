import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "public", "data", "college-degrees.json")


def c(name, credits, group):
    """法規只列課名，沒有課號與識別碼，因此以課名比對。"""
    return {"name": name, "credits": credits, "group": group}


def many(group, *pairs):
    return [c(name, credits, group) for name, credits in pairs]


degrees = []


def degree(code, college, name, total, published, rules, groups, courses, requirements=None,
           gen_ed_domains=None, group_rules=None):
    entry = {
        "code": code,
        "college": college,
        "name": name,
        "total": total,
        "published": published,
        "rules": rules,
        "requirements": requirements or {},
        "groups": groups,
        "groupRules": group_rules or [],
        "courses": courses,
    }
    if gen_ed_domains:
        entry["genEdDomains"] = gen_ed_domains
    degrees.append(entry)


